"""Camera calibration for the BEKO RealSense, loaded from the camera YAML.

The YAML is generated by `bag_inspect.py`. The `depth_to_color` rotation is stored
column-major as in the ROS message and is reshaped here, and only here.
"""

from dataclasses import dataclass, replace
from pathlib import Path

import numpy as np
import yaml
from loguru import logger

TOP_LEVEL_KEYS = ("depth_aligned", "depth_scale", "color", "depth", "depth_to_color")
INTRINSICS_KEYS = (
    "width",
    "height",
    "fx",
    "fy",
    "cx",
    "cy",
    "distortion_model",
    "coefficients",
)
EXTRINSICS_KEYS = ("rotation_column_major", "translation")


@dataclass(frozen=True)
class Intrinsics:
    width: int
    height: int
    fx: float
    fy: float
    cx: float
    cy: float
    distortion_model: str
    coefficients: tuple[float, ...]


@dataclass(frozen=True)
class Extrinsics:
    """Transform from depth to color frame: p_color = rotation @ p_depth + t."""

    rotation: np.ndarray  # (3, 3)
    translation: np.ndarray  # (3,), meters


@dataclass(frozen=True)
class CameraCalibration:
    """Typed contents of the camera YAML."""

    color: Intrinsics
    depth: Intrinsics
    depth_to_color: Extrinsics
    depth_aligned: bool
    depth_scale: float  # meters per depth unit


def _require(block: dict, keys: tuple[str, ...], name: str) -> None:
    if not isinstance(block, dict):
        raise ValueError(f"Camera config: '{name}' must be a mapping.")
    missing = [key for key in keys if key not in block]
    if missing:
        raise ValueError(f"Camera config: '{name}' is missing keys {missing}.")


def _intrinsics(block: dict, name: str) -> Intrinsics:
    _require(block, INTRINSICS_KEYS, name)
    return Intrinsics(
        width=int(block["width"]),
        height=int(block["height"]),
        fx=float(block["fx"]),
        fy=float(block["fy"]),
        cx=float(block["cx"]),
        cy=float(block["cy"]),
        distortion_model=str(block["distortion_model"]),
        coefficients=tuple(float(c) for c in block["coefficients"]),
    )


def _extrinsics(block: dict) -> Extrinsics:
    _require(block, EXTRINSICS_KEYS, "depth_to_color")
    rotation = np.array(block["rotation_column_major"], dtype=np.float64)
    translation = np.array(block["translation"], dtype=np.float64)
    if rotation.shape != (9,) or translation.shape != (3,):
        raise ValueError(
            "Camera config: depth_to_color needs 9 rotation and 3 translation values."
        )
    return Extrinsics(rotation.reshape(3, 3, order="F"), translation)


def load_calibration(
    path: str | Path, frame_size: tuple[int, int]
) -> CameraCalibration:
    """Load the camera YAML; scale the color intrinsics to `frame_size` (w, h)."""
    with open(path) as f:
        config = yaml.safe_load(f)
    _require(config, TOP_LEVEL_KEYS, "root")

    color = _intrinsics(config["color"], "color")
    width, height = frame_size
    if (width, height) != (color.width, color.height):
        sx, sy = width / color.width, height / color.height
        logger.warning(
            f"Frame size {width}x{height} differs from calibration "
            f"{color.width}x{color.height}; scaling color intrinsics."
        )
        color = replace(
            color,
            width=width,
            height=height,
            fx=color.fx * sx,
            cx=color.cx * sx,
            fy=color.fy * sy,
            cy=color.cy * sy,
        )

    return CameraCalibration(
        color=color,
        depth=_intrinsics(config["depth"], "depth"),
        depth_to_color=_extrinsics(config["depth_to_color"]),
        depth_aligned=bool(config["depth_aligned"]),
        depth_scale=float(config["depth_scale"]),
    )
